test('图片校验：格式、伪装内容、大小和数量', () => {
  const image = validateImages([upload()])[0];
  assert.equal(image.mime, 'image/png'); assert.ok(image.size > 0);
  assert.throws(() => validateImages([{ dataUrl: 'data:image/svg+xml;base64,PHN2Zz4=' }]), /只支持/);
  assert.throws(() => validateImages([{ dataUrl: pixel.replace('image/png', 'image/jpeg') }]), /不匹配/);
  assert.throws(() => validateImages([{ dataUrl: 'data:image/png;base64,' + 'A'.repeat(6000000) }]), /4 MB/);
  assert.throws(() => validateImages(Array.from({ length: 7 }, upload)), /最多 6/);
  assert.throws(() => validateImages([upload()], Array.from({ length: 6 }, () => image)), /最多 6/);
  assert.throws(() => validateImages([upload()], [{ size: IMAGE_LIMITS.totalBytes }]), /12 MB/);
  assert.throws(() => validateImages({}), /列表/);
});
