test('图片作为多模态块发送，文本上下文不包含 base64；后续仍可引用', async () => {
  const images = validateImages([upload()]);
  let sent;
  const client = new ModelClient({ baseUrl: 'https://example.invalid', apiKey: 'test', model: 'deepseek-flash', jsonMode: 'json_object', timeout: 1000 }, async (_, options) => {
    sent = JSON.parse(options.body);
    return { ok: true, json: async () => ({ choices: [{ finish_reason: 'stop', message: { content: JSON.stringify({ goal: '读图', learningPath: { currentUnderstanding: '未知', targetUnderstanding: '读懂代码', missingLink: '待确认', basis: '用户请求', nextMove: 'clarify' }, queries: [], gaps: [] }) } }] }) };
  });
  const user = { id: 'u', content: '请解释图片', imageIds: [images[0].id] };
  const context = contextFor({ goal: '', images, messages: [user], gaps: [], evidence: [] }, user);
  assert.ok(!JSON.stringify(context).includes('base64'));
  await client.generate('plan', '按图分析', context, images);
  const content = sent.messages[1].content;
  assert.ok(Array.isArray(content));
  assert.equal(content.filter(block => block.type === 'image_url').length, 1);
  assert.equal(content.find(block => block.type === 'image_url').image_url.url, pixel);
  assert.equal(typeof sent.messages[0].content, 'string');
});
test('补图不误当成作答，后续模型调用保留历史图片', async t => {
  const config = await setup(t); config.mode = 'live';
  const store = new Store(config.dataDir); await store.init();
  const session = store.create({ title: '图文' });
  session.check = { id: 'q', skillId: 'g', question: '旧题', rubric: '答案', kind: 'diagnostic' };
  session.gaps = [{ id: 'g', title: '概念', status: 'hypothesis', evidenceIds: [] }];
  const calls = [];
  const model = { generate: async (type, prompt, context, images) => {
    calls.push({ type, images: images?.length || 0 });
    if (type === 'plan') return { goal: '理解截图', queries: [], gaps: [] };
    if (type === 'grade') throw new Error('补图不能被评分');
    return { reply: '图片内容', focusId: 'g', check: null, suggestions: [], sourceIds: [] };
  } };
  const engine = new LearningEngine(config, store, { model });
  await engine.start(session, '补充这张图', 'answer', false, validateImages([upload()]));
  await Promise.all([...engine.pending]);
  assert.equal(session.run.status, 'done');
  assert.deepEqual(calls.map(c => c.type), ['plan', 'coach']);
  assert.ok(calls.every(c => c.images === 1)); assert.equal(session.evidence.length, 0);
  await engine.start(session, '继续解释');
  await Promise.all([...engine.pending]);
  assert.ok(calls.every(c => c.images === 1));
  const restored = new Store(config.dataDir); await restored.init();
  assert.equal(restored.get(session.id).images[0].dataUrl, pixel);
});
test('图片请求失败后重试不重复保存图片', async t => {
  const config = await setup(t); config.mode = 'live';
  const store = new Store(config.dataDir); await store.init();
  const session = store.create({ title: '重试' });
  const engine = new LearningEngine(config, store, { model: { generate: async () => { throw new Error('failure'); } } });
  await engine.start(session, '图片', 'answer', false, validateImages([upload()]));
  await Promise.all([...engine.pending]);
  await engine.start(session, '', 'answer', true); await Promise.all([...engine.pending]);
  assert.equal(session.images.length, 1); assert.equal(session.messages.length, 1);
});
test('图片 API：只发图片、读取原图、导出、错误隔离和旧会话兼容', async t => {
  const config = await setup(t);
  const app = await createApp(config);
  await new Promise(resolve => app.server.listen(0, '127.0.0.1', resolve));
  t.after(async () => { await Promise.allSettled([...app.engine.pending]); await new Promise(resolve => app.server.close(resolve)); });
  const base = 'http://127.0.0.1:' + app.server.address().port;
  const post = (route, payload) => fetch(base + route, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(payload) });
  const session = await (await post('/api/sessions', { title: '截图' })).json();
  const route = '/api/sessions/' + session.id;
  assert.equal((await post(route + '/messages', { images: [{ dataUrl: 'evil' }] })).status, 400);
  assert.equal(app.store.get(session.id).messages.length, 0);
  assert.equal((await post(route + '/messages', { images: [upload()] })).status, 202);
  await Promise.all([...app.engine.pending]);
  const snapshot = await (await fetch(base + route)).json();
  assert.equal(snapshot.messages[0].imageIds[0], snapshot.images[0].id);
  assert.equal(snapshot.images[0].dataUrl, undefined);
  assert.match(snapshot.messages.at(-1).content, /演示不能识别图片/);
  const image = await fetch(base + snapshot.images[0].url);
  assert.equal(image.headers.get('content-type'), 'image/png');
  assert.equal(Buffer.from(await image.arrayBuffer()).toString('base64'), pixel.split(',')[1]);
  const exported = await (await fetch(base + route + '/export')).json();
  assert.equal(exported.images[0].dataUrl, pixel);
  const other = await (await post('/api/sessions', { title: '另一个会话' })).json();
  assert.equal((await fetch(base + '/api/sessions/' + other.id + '/images/' + snapshot.images[0].id)).status, 404);
  const legacy = app.store.create({ title: '旧会话' }); delete legacy.images; await app.store.save(legacy);
  const restored = new Store(config.dataDir); await restored.init(); assert.deepEqual(restored.get(legacy.id).images, []);
});
