def context_for(session, user):
    return dict(
        target=session.get("goal", ""), previousLearningPath=session.get("learningPath"),
        material=session.get("material", ""), materialName=session.get("materialName", ""),
        images=image_metadata(session.get("images", [])),
        history=[{key: message[key] for key in ("id", "role", "content", "action", "imageIds") if key in message}
                 for message in session["messages"][-14:]],
        gaps=session["gaps"], recentEvidence=session["evidence"][-8:], currentCheck=session.get("check"),
        user={key: user[key] for key in ("id", "content", "action", "imageIds") if key in user})
